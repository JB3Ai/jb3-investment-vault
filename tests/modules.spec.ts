test('rotary pointer input advances selection', async ({ page }) => {
  const dial = page.getByRole('slider', { name: 'Context section' })
  // Real pointer movement is exercised in desktop Chromium.
  await dial.scrollIntoViewIfNeeded()
  const box = await dial.boundingBox()
  if (box) {
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2 + 70, box.y + box.height / 2 - 20, { steps: 5 })
    await page.mouse.up()
    await expect(dial).not.toHaveAttribute('aria-valuenow', '1')
  }
})

test('touch drag selects another context section', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile', 'Touch-specific mobile check')
  const dial = page.getByRole('slider', { name: 'Context section' })
  await dial.scrollIntoViewIfNeeded()
  const box = await dial.boundingBox()
  expect(box).not.toBeNull()
  const x = box!.x + box!.width / 2, y = box!.y + box!.height / 2
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 35, y: y - 25 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(dial).not.toHaveAttribute('aria-valuenow', '1')
  await cdp.detach()
})
