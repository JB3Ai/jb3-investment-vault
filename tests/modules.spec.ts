test('financial assumptions recalculate and reset', async ({ page }) => {
  await page.getByRole('button', { name: 'Open Financial Forecast', exact: true }).click()
  const totals = page.locator('.forecast-totals')
  const original = await totals.textContent()
  await page.getByLabel('Starting monthly revenue').fill('0')
  await expect(totals).not.toHaveText(original!)
  await expect(totals.locator('.negative')).toBeVisible()
  await page.getByRole('button', { name: 'Reset assumptions' }).click()
  await expect(totals).toHaveText(original!)
  await page.getByLabel('Forecast horizon').selectOption('6')
  await page.getByText('View the monthly model and calculation method').click()
  await expect(page.locator('tbody tr')).toHaveCount(6)
})
